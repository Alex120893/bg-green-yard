export function searchPlantDatabase(query: string): string {
  const lowerQuery = query.toLowerCase();
  let relevantInfo = "";

  // Търси в растенията
  for (const plant of plantDatabase.plants) {
    if (
      plant.name.toLowerCase().includes(lowerQuery) ||
      plant.description.toLowerCase().includes(lowerQuery) ||
      plant.category.toLowerCase().includes(lowerQuery)
    ) {
      relevantInfo += `\n**${plant.name}** (${plant.category})\n`;
      relevantInfo += `${plant.description}\n`;
      relevantInfo += "Насоки за грижа:\n";
      plant.care.forEach(tip => {
        relevantInfo += `• ${tip}\n`;
      });
    }
  }

  // Търси в грижата на тревата
  if (lowerQuery.includes("трева") || lowerQuery.includes("газон") || lowerQuery.includes("косене")) {
    for (const item of plantDatabase.lawnCare) {
      if (item.title.toLowerCase().includes(lowerQuery)) {
        relevantInfo += `\n**${item.title}**\n`;
        item.tips.forEach(tip => {
          relevantInfo += `• ${tip}\n`;
        });
      }
    }
  }

  // Търси в общите съветы
  for (const [key, value] of Object.entries(plantDatabase.generalTips)) {
    if (lowerQuery.includes(key) || (typeof value === "string" && value.toLowerCase().includes(lowerQuery))) {
      relevantInfo += `\n**Съвет**: ${value}\n`;
    }
  }

  return relevantInfo || "Не намерих информация в базата ми за вашия вопрос. Опитайте с други ключови думи.";
}
