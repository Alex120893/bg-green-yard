import assert from 'node:assert/strict';
const base = process.argv[2] ?? 'http://127.0.0.1:3100';
const path = '/bg/polivni-sistemi-sofia';
const url = `https://bg-greenyard.com${path}`;
const r = await fetch(base + path);
assert.equal(r.status, 200);
const html = await r.text();
assert.equal((html.match(/<h1(?:\s|>)/g) ?? []).length, 1);
for (const text of ['Поливни системи София', 'Решение за всяка зона на градината', 'От огледа до първото поливане', 'Въпроси за поливните системи']) assert.ok(html.includes(text));
assert.ok(html.includes(`rel="canonical" href="${url}"`));
assert.ok(html.includes('property="og:image" content="https://bg-greenyard.com/images/gallery/trevna-plosht-sofia.jpg"'));
assert.ok(html.includes('/video_2026-11-27_19-38-23.mp4'));
assert.equal((html.match(/<video(?:\s|>)/g) ?? []).length, 1);
assert.equal((html.match(/<li[^>]*data-irrigation-step/g) ?? []).length, 3);
assert.equal((html.match(/<details/g) ?? []).length, 5);
assert.ok(html.includes('href="/bg/contact?service=irrigation"'));
assert.ok(!html.includes('aria-controls="winter-maintenance-video"'));
const json = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map(m => JSON.parse(m[1]));
assert.ok(json.some(s => s['@type'] === 'Service' && s.url === url));
assert.equal((await fetch(base + '/en/polivni-sistemi-sofia')).status, 404);
console.log('Irrigation page: canonical, metadata, video, headings, three work steps, five FAQs, contact preselection link and Service JSON-LD passed.');
